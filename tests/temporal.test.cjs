const assert=require("node:assert/strict");
const t=require("../assets/temporal.js");
assert.equal(t.validDate("2024-02-29"),true);
assert.equal(t.validDate("2025-02-29"),false);
assert.equal(t.validDate("2026-04-31"),false);
assert.deepEqual(t.monthBounds("2024-02"),{from:"2024-02-01",to:"2024-02-29"});
assert.deepEqual(t.monthBounds("2026-02"),{from:"2026-02-01",to:"2026-02-28"});
assert.deepEqual(t.normalizeRange("2026-10-09","2026-10-01"),{from:"2026-10-01",to:"2026-10-09"});
assert.throws(()=>t.monthBounds("2026-13"),/Invalid month/);
assert.throws(()=>t.normalizeRange("2026-02-30",""),/Invalid start date/);
assert.deepEqual(t.monthlyCounts([{date:"2026-10-08"},{date:"2026-09-01"},{date:"2026-10-07"},{date:"bad"}]),[{month:"2026-09",count:1},{month:"2026-10",count:2}]);
let changes=0;const state=t.createTemporalState(()=>changes++);
state.selectMonth("2026-10");
assert.deepEqual(state.getRange(),{from:"2026-10-01",to:"2026-10-31"});
assert.equal(state.matches("2026-10-08"),true);
assert.equal(state.matches("2026-09-30"),false);
assert.equal(state.filter([{date:"2026-10-01"},{date:"2026-11-01"}]).length,1);
state.clear();
assert.equal(state.matches("2026-11-01"),true);
assert.equal(changes,2);
console.log("Temporal module: 16 assertions passed");
